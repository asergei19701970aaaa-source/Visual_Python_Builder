def point_help(
    component_type: str,
    port_name: str,
    caption: str = "",
    kind: str = "",
    description: str = "",
) -> str:
    """Return a short operational description without generic filler."""
    if description.strip():
        return description.strip()
    exact = POINT_HELP.get(component_type, {}).get(port_name)
    if exact:
        return exact
    if kind == "work_in":
        return f"Запускает действие «{caption or port_name}»."
    if kind == "event_out":
        return f"Событие «{caption or port_name}» после выполнения ноды."
    if kind == "data_in":
        return f"Входное значение: «{caption or port_name}»."
    if kind == "data_out":
        return f"Выходное значение: «{caption or port_name}»."
    return f"Точка «{caption or port_name}»."